"""Qualify #216 natively: a source_upsert refresh reports whether a block's number, interface or body changed, next to the
compiler comparison, without inferring a cause. Owned scratch only; never a user project."""
import argparse
import json
from pathlib import Path
import uuid

from smoke_mcp import Client, ROOT

CALLEE = 'FUNCTION_BLOCK "RefreshCallee"\nVERSION : 0.1\nVAR_INPUT\n a : Bool;\nEND_VAR\nVAR\n s : Int;\nEND_VAR\nBEGIN\n IF #a THEN #s := #s + 1; END_IF;\nEND_FUNCTION_BLOCK\n'
CALLER = 'FUNCTION_BLOCK "RefreshCaller"\nVERSION : 0.1\nVAR\n callee : "RefreshCallee";\nEND_VAR\nBEGIN\n #callee(a := TRUE);\nEND_FUNCTION_BLOCK\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--artifacts', type=Path, required=True)
    parser.add_argument('--host', type=Path, default=ROOT / 'src/TiaMcp.Host/bin/Debug/net10.0-windows/TiaMcp.Host.exe')
    parser.add_argument('--worker', type=Path, default=ROOT / 'src/TiaMcp.Openness.V21/bin/Debug/net48/TiaMcp.Openness.V21.exe')
    args = parser.parse_args()
    root = args.artifacts.resolve()
    root.mkdir(parents=True, exist_ok=False)
    client = Client(args.host.resolve(), 180, ['--worker', str(args.worker.resolve()), '--artifacts', str(root)])
    report = {'completed': False, 'steps': []}

    def record(name, data):
        report['steps'].append({'name': name, 'result': data})
        (root / 'report.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
        print(name, flush=True)
        return data

    def upsert(label, source, names):
        prepared = client.tool('change_prepare', {'kind': 'source_upsert', 'plcPath': plc, 'payload': {
            'language': 'SCL', 'source': source, 'expectedBlockNames': names}})
        applied = client.tool('change_apply', {'changeId': prepared['changeId'], 'previewHash': prepared['previewHash'],
                                               'idempotencyKey': uuid.uuid4().hex, 'checkpointSave': True, 'compile': True, 'save': True})
        assert applied['state'] == 'applied', applied['state']
        refresh = next((r for r in applied['readbacks'] if r.get('role') == 'source-refresh-comparison'), None)
        delta = applied['compile']['baselineComparison']
        return record(label, {'refresh': refresh, 'compilerSucceeded': applied['compile']['compilerSucceeded'],
                              'baseline': {k: delta.get(k) for k in ('complete', 'existingCount', 'resolvedCount', 'introducedCount')}})

    try:
        client.request('initialize', {'protocolVersion': '2025-11-25', 'capabilities': {}, 'clientInfo': {'name': 'source-refresh', 'version': '1'}})
        client.notify('notifications/initialized')
        assert record('owned start', client.tool('tia_start'))['ownsPortalProcess'] is True
        record('owned scratch', client.tool('tia_create_scratch'))
        plc = client.tool('project_inventory')['plcs'][0]['path']
        created = upsert('create callee and caller', CALLEE + CALLER, ['RefreshCallee', 'RefreshCaller'])
        assert created['refresh'] is not None and created['refresh']['blocks'] == [], created['refresh']

        generated = client.tool('block_read', {'plcPath': plc, 'blockName': 'RefreshCaller', 'format': 'generatedSource'})
        files = [a for a in generated['export']['artifacts'] if str(a.get('path', '')).endswith('.scl')]
        assert len(files) == 1, generated['export']
        source = Path(files[0]['path']).read_text(encoding='utf-8-sig')
        record('caller source generated by TIA', {'artifact': files[0], 'removedExternalSources': generated['export']['removedExternalSources']})

        same = upsert('refresh the caller from its own generated source', source, ['RefreshCaller'])
        r = same['refresh']
        assert r['logicChanged'] is False and r['interfaceChanged'] is False and r['numbersPreserved'] is True, r
        assert same['baseline']['complete'] is True and same['baseline']['introducedCount'] == 0, same['baseline']

        assert 'a := TRUE' in source, source
        changed = upsert('a real source change is reported as a logic change', source.replace('a := TRUE', 'a := FALSE', 1), ['RefreshCaller'])
        r = changed['refresh']
        assert r['logicChanged'] is True and r['interfaceChanged'] is False and r['numbersPreserved'] is True, r
        report['completed'] = True
    finally:
        record('owned worker shutdown', client.close())
        (root / 'report.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    return 0 if report['completed'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
