"""Generate or check docs/reference/error-codes.md, the registry of error codes the Host and workers raise.

A code is stable (frozen at 1.0, contract freeze policy Q3) when it is an outcome, recovery or gate code
listed in GATE_CODES, or when a reference or guide page, a contract schema or a Host tool description names
it. Every other code is a detail code that may change in a minor release.
"""
import argparse
import collections
import re

from release_matrix import ROOT

PAGE = "docs/reference/error-codes.md"
# Outcome, recovery and gate codes clients branch on, whether or not a page names them yet.
GATE_CODES = {"OutcomeUnknown", "RecoveryRequired", "ReconciliationIncomplete", "OwnedInstanceRequired", "OwnedScratchRequired",
              "NativeWorkersDisabled", "RuntimeAcknowledgementRequired", "ProtocolMismatch", "SafetyBoundary", "UnsupportedCapability"}
# shortcut: codes are found by these source patterns only (a coded exception, an Error/Fail helper or a "code" field set
# to a literal); a code built from a variable is missed. Upgrade to a Roslyn scan if the registry is found incomplete.
RAISE = re.compile(r'(?:\b(?:Bridge|Simulator|Graph|PlcComponent|BridgeOperation)Exception|\bError|\bFail)\(\s*"([A-Z][A-Za-z0-9]+)"'
                   r'|\bnew\(\s*"([A-Z][A-Za-z0-9]+)",\s*"[^"]* '  # target-typed: a code, then a message with a space
                   r'|\["code"\]\s*=\s*"([A-Z][A-Za-z0-9]+)"|\bcode:\s*"([A-Z][A-Za-z0-9]+)"')
DESCRIPTION = re.compile(r'\[Description\((.*?)\)\]', re.S)


def raised():
    """code -> set of source projects (src/<project>) that raise it."""
    codes = collections.defaultdict(set)
    for path in (ROOT / "src").rglob("*.cs"):
        if any(part in ("bin", "obj") for part in path.parts):
            continue
        project = path.relative_to(ROOT / "src").parts[0]
        for match in RAISE.finditer(path.read_text(encoding="utf-8", errors="replace")):
            codes[next(g for g in match.groups() if g)].add(project)
    return codes


def documented_text():
    parts = [p.read_text(encoding="utf-8") for folder in ("docs/reference", "docs/guides") for p in (ROOT / folder).rglob("*.md")
             if p.relative_to(ROOT).as_posix() != PAGE]
    parts += [p.read_text(encoding="utf-8") for p in (ROOT / "contracts").glob("*.schema.json")]
    for path in (ROOT / "src/TiaMcp.Host").rglob("*.cs"):
        parts += DESCRIPTION.findall(path.read_text(encoding="utf-8", errors="replace"))
    return "\n".join(parts)


def registry():
    """code -> (class, projects), sorted by code."""
    text = documented_text()
    words = set(re.findall(r"[A-Za-z0-9]+", text))
    return {code: ("stable" if code in GATE_CODES or code in words else "detail", sorted(projects))
            for code, projects in sorted(raised().items())}


def stable_codes():
    return sorted(code for code, (kind, _) in registry().items() if kind == "stable")


def render(entries):
    stable = sum(1 for kind, _ in entries.values() if kind == "stable")
    lines = [
        "# Error codes",
        "",
        "<!-- Generated by scripts/error_registry.py from src/ and the documentation; do not edit. -->",
        "",
        f"Every error code the Host and the workers raise: {len(entries)} codes, {stable} stable and",
        f"{len(entries) - stable} detail. Errors arrive in one envelope, `{{\"error\": {{\"code\", \"message\", ...}}}}`",
        "with `isError`; the [MCP surface](mcp-surface.md) page describes it.",
        "",
        "**Class** follows the [contract freeze policy](../plans/contract-freeze-policy.md#q3-which-error-codes-are-frozen):",
        "a `stable` code is an outcome, recovery or gate code, or one a reference or guide page, a contract",
        "schema or a tool description names; from 1.0 it is not renamed or removed within a major version.",
        "A `detail` code may change in a minor release; branch on it only together with its message.",
        "**Raised in** names the source projects that raise the code.",
        "",
        "| Code | Class | Raised in |",
        "| --- | --- | --- |",
    ]
    lines += [f"| `{code}` | {kind} | {', '.join(projects)} |" for code, (kind, projects) in entries.items()]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed page is stale")
    args = parser.parse_args()
    entries = registry()
    missing = sorted(GATE_CODES - set(entries))
    if missing:
        raise SystemExit("Gate codes no source raises: " + ", ".join(missing))
    text = render(entries)
    target = ROOT / PAGE
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{PAGE} is stale; run python -B scripts/error_registry.py")
        print(f"PASS {PAGE} matches the source.")
        return
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {PAGE}: {len(entries)} codes.")


if __name__ == "__main__":
    main()
