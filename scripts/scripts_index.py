"""Generate scripts/README.md, the index of this folder; --check fails when the committed index is stale.

Every file directly in scripts/ and every scripts/tests/test_*.py is listed under exactly one heading. PowerShell entry
points are grouped by hand in ENTRY_POINTS below (a new .ps1 fails the check until it is added there); everything else is
grouped by name and summarised from its module docstring.
"""
import argparse
import ast
import pathlib
import re
import sys
import warnings
from collections import defaultdict

SCRIPTS = pathlib.Path(__file__).resolve().parent
README = SCRIPTS / "README.md"

# Grouped by purpose only; prerequisites per runner are in docs/reference/validation-runners.md and each script's help.
ENTRY_POINTS = {
    "Setup, registration and machine configuration": [
        "Setup-TiaMcp.ps1", "Register-TiaOpennessApplication.ps1", "Register-DevOpennessWorker.ps1",
        "Test-TiaOpennessRegistration.ps1", "OpennessRegistration.Helpers.ps1", "New-McpConfiguration.ps1",
        "Set-SimulatorAllocationPolicy.ps1",
    ],
    "Build, package and launch": [
        "Build.ps1", "New-IsolatedBuild.ps1", "Build-HmiWorkerSnapshot.ps1", "Package.ps1", "Verify-TiaMcpBundle.ps1",
        "Start-TiaMcp.ps1", "Publish-AddIn.ps1", "Refresh-Contracts.ps1",
    ],
    "Test runners": [
        "Test-Offline.ps1", "Test-OfflinePackage.ps1", "Test-OpcUaOffline.ps1", "Test-OpennessRegistrationLogic.ps1",
        "Test-Deployment.ps1", "Test-AddInSandbox.ps1", "Test-WorkerCompile.ps1", "Test-EnvironmentDiagnostics.ps1",
        "Test.ps1", "Test-Libraries.ps1", "Test-ProjectExplorer.ps1", "Test-RetainedFixtures.ps1", "Test-AddInOwner.ps1",
        "Test-DeploymentReliability.ps1", "Test-WorkstationBoundaries.ps1", "Test-InventoryExcel.ps1",
        "Test-RuntimeCaptureDiskFull.ps1",
    ],
    "Qualification and guest runs": [
        "qualify_hmi_atomic_output.ps1", "qualify_library_hmi.ps1", "verify_library_optional_hmi.ps1",
        "Enable-GuestAccess.ps1", "Invoke-GuestQualification.ps1", "Run-GuestTest.ps1", "Test-GuestAccessStartup.ps1",
    ],
    "Environment and API inspection": [
        "Probe-Environment.ps1", "Test-TiaMcpEnvironment.ps1", "Inspect-PublicApi.ps1", "Inspect-OpcUaApi.ps1",
    ],
}

GROUPS = [  # prefix, count-table label, section heading
    ("qualify_", "Qualification runners (`qualify_*`)", "Qualification runners"),
    ("probe_", "Probes (`probe_*.py`)", "Probes"),
    ("verify_", "Verifiers (`verify_*.py`)", "Verifiers"),
    ("test_", "Test harnesses kept in `scripts/` (`test_*.py`)", "Test harnesses kept in scripts/"),
]


def first_sentence(text):
    text = " ".join(text.split())
    text = re.split(r"(?<=[.!?])\s", text)[0].replace("|", "\\|")
    return text if len(text) <= 140 else text[:137].rstrip() + "..."


def synopsis(path):
    """The comment-based help .SYNOPSIS of a PowerShell script, if it has one."""
    match = re.search(r"^\s*\.SYNOPSIS\s*\n((?:\s*[^.\s#][^\n]*\n)+)", path.read_text(encoding="utf-8-sig"), re.M)
    return first_sentence(match.group(1)) if match else ""


def summary(path):
    if path.suffix == ".ps1":
        return synopsis(path)
    if path.suffix != ".py":
        return ""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", SyntaxWarning)
        try:
            doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")))
        except SyntaxError:
            return ""
    if not doc:
        return ""
    return first_sentence(doc.split("\n\n")[0])


def names(items, folder=""):
    return ", ".join(f"[`{name}`]({folder}{name})" for name in items)


def render():
    files = sorted(p.name for p in SCRIPTS.iterdir() if p.is_file() and p.name != "README.md")
    tests = sorted(p.name for p in (SCRIPTS / "tests").glob("test_*.py"))
    folders = sorted(p.name for p in SCRIPTS.iterdir() if p.is_dir() and not p.name.startswith(("_", ".")))
    mapped = {name for group in ENTRY_POINTS.values() for name in group}
    ps1 = {name for name in files if name.endswith(".ps1")}
    if ps1 - mapped or mapped - ps1:
        raise SystemExit("scripts_index.py ENTRY_POINTS is out of step with scripts/*.ps1: missing "
                         + ", ".join(sorted(ps1 - mapped)) + "; absent " + ", ".join(sorted(mapped - ps1)))
    rest = [name for name in files if name not in ps1]
    grouped = {prefix: [n for n in rest if n.startswith(prefix)] for prefix, _, _ in GROUPS}
    helpers = [n for n in rest if n.endswith(".py") and not any(n.startswith(p) for p, _, _ in GROUPS)]
    other = [n for n in rest if not n.endswith(".py") and not any(n.startswith(p) for p, _, _ in GROUPS)]

    out = ["# scripts/", "",
           "<!-- Generated by scripts/scripts_index.py; run `python -B scripts/scripts_index.py` after adding, moving or"
           " removing a script. scripts/tests/test_scripts_index.py fails while this file is stale. -->", "",
           "Entry points, qualification runners, helper modules and tests. Paths that curated evidence, historical"
           " records or `contracts/api-coverage/implementation-bindings.v1.json` cite stay where they are, so the"
           " qualification runners, probes and the cited `test_*.py` harnesses remain directly in this folder.", "",
           "| Location | Files |", "| --- | ---: |",
           f"| PowerShell entry points (`*.ps1`) | {len(ps1)} |"]
    for prefix, title, _ in GROUPS:
        out.append(f"| {title} | {len(grouped[prefix])} |")
    out += [f"| Helper modules and tools (`*.py`) | {len(helpers)} |",
            f"| Unit tests in [`tests/`](tests/) | {len(tests)} |",
            f"| Other files | {len(other)} |", ""]

    out += ["## PowerShell entry points", "",
            "Documented user commands; run them from the repository root, for example `./scripts/Test-Offline.ps1`."
            " Which ones need TIA Portal, PLCSIM or Siemens reference assemblies is in"
            " [validation runners](../docs/reference/validation-runners.md) and each script's help; the summary is"
            " the script's `.SYNOPSIS` where it has one.", ""]
    for title, group in ENTRY_POINTS.items():
        out += [f"### {title}", "", "| Script | Synopsis |", "| --- | --- |"]
        out += [f"| [`{name}`]({name}) | {summary(SCRIPTS / name)} |" for name in sorted(group)]
        out.append("")

    out += ["## Qualification runners", "",
            "Most `qualify_*` scripts drive native TIA Portal or PLCSIM qualification and write the raw reports that"
            " `curate_evidence.py` turns into `evidence/` summaries; others run against the built Host and fixture"
            " servers only, and `Test-Offline.ps1` invokes several of those. Read a runner's docstring before running"
            " it, and run native ones only on a workstation and targets you own. Grouped by the word after"
            " `qualify_`.", ""]
    domains = defaultdict(list)
    for name in grouped["qualify_"]:
        domains[name[len("qualify_"):].split("_")[0].split(".")[0]].append(name)
    small = sorted(n for d, items in domains.items() if len(items) < 2 for n in items)
    out += ["| Domain | Runners |", "| --- | --- |"]
    out += [f"| {domain} | {names(items)} |" for domain, items in sorted(domains.items()) if len(items) >= 2]
    if small:
        out.append(f"| other | {names(small)} |")
    out.append("")

    for prefix, _, heading in GROUPS[1:]:
        intro = {
            "probe_": "One-off native investigations. Each is cited by a verification record or evidence, so even dated"
                      " probes keep their path.",
            "verify_": "Checks of retained native outputs or built artifacts.",
            "test_": "Harnesses that stay here because curated evidence or historical records cite their path, a runner"
                     " invokes them by path with arguments (`python -B scripts/test_x.py --host ...`), source or build"
                     " files name them, or modules in this folder import them. `Test-Offline.ps1` discovers the"
                     " unittest ones together with `tests/`.",
        }[prefix]
        out += [f"## {heading}", "", intro, ""]
        if prefix == "test_":
            out += [names(grouped[prefix]), ""]
        else:
            out += ["| Script | Summary |", "| --- | --- |"]
            out += [f"| [`{n}`]({n}) | {summary(SCRIPTS / n)} |" for n in grouped[prefix]]
            out.append("")

    out += ["## Helper modules and tools", "",
            "Shared Python modules imported by runners and tests, plus generators and validators (for example"
            " `curate_evidence.py`, `api_coverage_bindings.py`, `release_matrix.py`).", "",
            "| Module | Summary |", "| --- | --- |"]
    out += [f"| [`{n}`]({n}) | {summary(SCRIPTS / n)} |" for n in helpers]
    out.append("")

    out += ["## Unit tests (`tests/`)", "",
            "Plain unittest modules that nothing cites by path. They import helpers from `scripts/` by module name, so"
            " run them through the runner or with both folders on the import path:", "",
            "```powershell", "./scripts/Test-Offline.ps1 -Suite Python",
            "$env:PYTHONPATH = 'scripts/tests;scripts'; python -B -m unittest test_offline_runner", "```", "",
            names(tests, "tests/"), ""]

    out += ["## Other files and folders", ""]
    out += [f"- [`{n}`]({n})" for n in other]
    out += [f"- [`{n}/`]({n}/)" for n in folders if n != "tests"]
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing when scripts/README.md is stale")
    args = parser.parse_args()
    text = render()
    current = README.read_text(encoding="utf-8").replace("\r\n", "\n") if README.exists() else None
    if args.check:
        if current != text:
            print("scripts/README.md is stale; run python -B scripts/scripts_index.py", file=sys.stderr)
            return 1
        return 0
    if current != text:
        README.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
