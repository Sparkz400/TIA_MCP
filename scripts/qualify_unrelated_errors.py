"""Qualify #221 natively: unchanged unrelated compiler findings do not fail a valid change.

One owned scratch: the scratch CPU, an F-CPU 1511F-1 PN (configureScratchSecurity, failsafeRuntimeAccess; scratch only) and
two more standard CPUs whose interfaces share one subnet and IP address. The address conflict keeps every block consistent
(so the full project fingerprint still works) and fails every device compile, standing in for the 4 November SENTRON error.

- safety_import_xml re-imports Main_Safety_RTG1 with a comment: applied, saved and read back with compilerSucceeded=false;
  baselineComparison lists the conflict as existing.
- In the same session, without restart or admission cleanup: a second device-compiled change (network_configure of the
  F-CPU), a PLC-scoped tag_create, and a consumer FC generated by source_upsert.
- network_configure moves one conflicting CPU to a free address: applied with the conflict reported as resolved.
- Negative: tag_set turns the consumed tag into Int, which breaks the consumer. CompileFailed, recovery_required, and the
  consumer error is the only introduced finding.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from library_native_harness import Harness, require
from probe_safety_kinds import catalog, change

MAIN = "Main_Safety_RTG1"
LIMITATIONS = [
    "Owned offline scratch only; the unrelated finding is a duplicate IP address between two otherwise empty standard CPUs.",
    "An inconsistent block on any PLC still stops preparation of kinds that need the full project fingerprint (see #218).",
    "The F-CPU's generated scratch user holds Full access including fail-safe (owned scratch only); no safety login, "
    "password, acceptance or download.",
]


def interface(h, device):
    rows = sorted((r for r in h.tool("hardware_inspect", {"maxItems": 2000})["items"]
                   if r["path"].startswith(device + "/") and r.get("network", {}).get("nodes")), key=lambda r: r["path"])
    require(rows, "No network interface under " + device)
    return rows[0]["path"], rows[0]["network"]["nodes"][0]["name"]


def comparison(applied, label):
    compile = applied.get("compile") or {}
    delta = compile.get("baselineComparison") or {}
    require(compile.get("compilerSucceeded") is True or (delta.get("complete") is True and delta.get("introducedErrorCount") == 0),
            "%s: baseline comparison does not accept the change: %s" % (label, delta))
    require("changed_project_saved" in applied["stages"], "%s was not saved: %s" % (label, applied["stages"]))
    return {"compilerSucceeded": compile.get("compilerSucceeded"), "errorCount": compile.get("errorCount"),
            **{k: delta.get(k) for k in ("existingCount", "resolvedCount", "introducedCount", "introducedErrorCount")}}


def body(h):
    p1 = h.owned_scratch("unrelated errors")
    status = h.tool("tia_session_status")["projects"][0]
    devices = "/projects/%s/devices/" % status["name"]
    fcpu = h.report["fCpu"] = catalog(h, "1511F-1 PN", "1511F-1 PN", "6ES7 ")[0]
    change(h, "hardware_add", {"typeIdentifier": fcpu["typeIdentifier"], "deviceName": "FStation", "itemName": "TiaMcpFPlc",
                               "configureScratchSecurity": True, "failsafeRuntimeAccess": True}, {})
    for n in (2, 3):
        change(h, "hardware_add", {"typeIdentifier": h.scratch_cpu, "deviceName": "Other%d" % n, "itemName": "OtherPlc%d" % n,
                                   "configureScratchSecurity": True}, {}, compile=False)
    plcs = {p["path"].split("/items/")[0]: p["path"] for p in h.tool("project_inventory", {"maxItems": 2000})["plcs"]}
    fplc = plcs[devices + "FStation"]
    for n in (2, 3):
        path, node = interface(h, devices + "Other%d" % n)
        change(h, "network_configure", {"hardwarePath": path, "nodeName": node, "subnetName": "Conflict",
                                        "attributes": {"Address": "192.0.2.10", "SubnetMask": "255.255.255.0"}}, {}, compile=False)

    xml = h.tool("block_read", {"plcPath": fplc, "blockName": MAIN})["xml"]
    require("<Text />" in xml, "The main safety block has no empty comment text to fill")
    applied = h.apply("safety_import_xml", {"xml": xml.replace("<Text />", "<Text>TiaMcp unrelated error</Text>", 1),
                                            "expectedBlockNames": [MAIN], "safetyAcknowledged": True})
    result = h.stage("safety import applies beside the unrelated conflict", lambda: comparison(applied, "safety_import_xml"))
    require(result["compilerSucceeded"] is False and result["existingCount"] > 0 and result["introducedErrorCount"] == 0,
            "The conflict was not reported as an existing finding: %s" % result)
    h.stage("safety import read back", lambda: require("TiaMcp unrelated error" in h.tool("block_read", {"plcPath": fplc, "blockName": MAIN})["xml"],
                                                       "The comment is not in the export") or True)

    path, node = interface(h, devices + "FStation")
    applied = h.apply("network_configure", {"hardwarePath": path, "nodeName": node, "subnetName": "FNet",
                                            "attributes": {"Address": "192.0.2.60", "SubnetMask": "255.255.255.0"}})
    result = h.stage("second device-compiled edit in the same session", lambda: comparison(applied, "network_configure"))
    require(result["existingCount"] > 0, "The conflict was not reported as existing: %s" % result)

    applied = h.apply("tag_create", {"tagTableName": "Default tag table", "name": "UnrelatedOk", "dataTypeName": "Bool", "logicalAddress": "%M70.0"})
    h.stage("PLC-scoped tag_create in the same session", lambda: comparison(applied, "tag_create"))
    source = 'FUNCTION "UnrelatedConsumer" : Bool\nVERSION : 0.1\nBEGIN\n IF "UnrelatedOk" THEN #UnrelatedConsumer := TRUE; ELSE #UnrelatedConsumer := FALSE; END_IF;\nEND_FUNCTION\n'
    applied = h.apply("source_upsert", {"language": "SCL", "source": source, "expectedBlockNames": ["UnrelatedConsumer"]})
    h.stage("consumer FC in the same session", lambda: comparison(applied, "source_upsert"))

    path, node = interface(h, devices + "Other3")
    applied = h.apply("network_configure", {"hardwarePath": path, "nodeName": node, "subnetName": "Conflict",
                                            "attributes": {"Address": "192.0.2.11", "SubnetMask": "255.255.255.0"}})
    result = h.stage("fixing the conflict reports resolved findings", lambda: comparison(applied, "network_configure"))
    require(result["resolvedCount"] > 0, "The fixed conflict was not reported as resolved: %s" % result)

    prepared = h.prepare("tag_set", {"tagTableName": "Default tag table", "memberName": "UnrelatedOk",
                                     "attributes": {"DataTypeName": "Int", "LogicalAddress": "%MW72"}})

    def introduced():
        error = h.call_error("change_apply", h.apply_args(prepared))
        require(error.get("code") == "CompileFailed", "Expected CompileFailed, observed %s" % error)
        status = h.tool("change_status", {"changeId": prepared["changeId"], "includeDetails": True})
        delta = (status.get("compile") or {}).get("baselineComparison") or {}
        require(status["state"] == "recovery_required" and delta.get("complete") is True and delta.get("introducedErrorCount", 0) >= 1,
                "Unexpected failed outcome: %s %s" % (status["state"], delta))
        errors = [row for row in delta["introduced"] if row[0] == "Error"]
        require(errors and all("UnrelatedConsumer" in json.dumps(row) for row in errors), "Introduced errors are not the consumer's: %s" % delta["introduced"])
        require("changed_project_saved" not in status["stages"], "A failed change was saved")
        return {"error": error["code"], "state": status["state"], "introduced": delta["introduced"],
                "compilerSucceeded": status["compile"].get("compilerSucceeded")}
    h.stage("an introduced finding still fails the change", introduced)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", type=Path, required=True)
    parser.add_argument("--worker", type=Path, required=True)
    parser.add_argument("--artifacts", type=Path, required=True)
    parser.add_argument("--timeout", type=int, default=900)
    parser.add_argument("--run-native", action="store_true")
    args = parser.parse_args()
    args.runner = __file__
    Harness(args, "ue_", "#221 unrelated compiler findings in one owned scratch", LIMITATIONS, []).run(body)
